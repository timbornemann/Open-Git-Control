const fs = require('node:fs');
const path = require('node:path');
const Ajv = require('ajv');
const standaloneCode = require('ajv/dist/standalone').default;
const prettier = require('prettier');

async function main() {
  const root = path.resolve(__dirname, '..');
  const examples = require('../src/tutorial/fixtures/structured-files.json');
  const contract = JSON.parse(examples['schema-contract'][0]);
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
  ajv.addSchema({ type: 'object' }, 'object');
  ajv.addSchema(contract, 'contract');
  const code = standaloneCode(ajv, { validateObject: 'object', validateContract: 'contract' });
  if (/\brequire\s*\(|\beval\s*\(|new Function\b/.test(code)) throw new Error('Practice schema validators must be self-contained and CSP-safe.');
  const output = path.join(root, 'src/tutorial/generated/practice-schema.mjs');
  const formatted = await prettier.format('// Generated by scripts/generate-tutorial-schema.cjs; do not edit.\n' + code, {
    ...(await prettier.resolveConfig(output)),
    parser: 'babel',
  });
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== formatted) throw new Error('Regenerate the practice schema validators.');
    console.log('Practice schema validators are current.');
    return;
  }
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, formatted);
  console.log('Generated CSP-safe practice schema validators.');
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
